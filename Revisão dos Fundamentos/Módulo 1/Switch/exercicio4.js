// Crie um sistema de notas por letras.
const nota = "C";

switch (nota) {
    case "A":
        console.log("Excelente.");
        break;

    case "B":
        console.log("Muito bom.");
        break;

    case "C":
        console.log("Bom.");
        break;

    case "D":
        console.log("Abaixo da média.");
        break;

    case "E":
        console.log("Recuperação.");
        break;

    default:
        console.log("Reprovado");
        break;
};