/*
===========================
COMANDOS BÁSICOS DO TERMINAL
===========================

1. dir
    - Lista todos os arquivos e pastas da pasta atual.


2. cd nome-da-pasta
    - Entra em uma pasta.
    - Exemplo:
        cd "readline - Terminal"


3. cd ..
    - Volta para a pasta anterior.


4. node arquivo.js
    - Executa um arquivo JavaScript com o Node.js.
    - Exemplo:
        node app.js


5. cls
    - Limpa o terminal.


6. exit
    - Fecha o terminal.

    
IMPORTANTE:
    - Se o nome do arquivo tiver espaços, use aspas.
    - Exemplo:
        node "exercicio 1.js"


BOAS PRÁTICAS:
    - Evite espaços no nome dos arquivos.
    - Prefira:
        exercicio1.js
        exercicio-1.js
        exercicio_1.js


ERROS COMUNS:

    "Cannot find module"
    - O Node não encontrou o arquivo.
    - Verifique:
        ✔ Se o nome está correto.
        ✔ Se você está na pasta certa.
        ✔ Se o arquivo realmente existe.


DICA:
    Sempre use "dir" antes de executar um arquivo para confirmar
    que ele está na pasta onde você está trabalhando.
*/